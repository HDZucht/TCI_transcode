#!/usr/bin/env python3
"""Write kit/tci-kit.toml: the kit's settings and one on/off line per msdr decoder.

Ends:       a config file that lists every decoder of the installed msdr, grouped the way msdr can run them together,
            each with its label, the program it needs and its input limits, so the operator only flips true/false.
Ways:       reads msdr's own decoder registry (msdr.decoder.registry.DECODERS), so the list follows the pinned msdr
            version instead of a hand-kept copy. Run it with msdr's Python. Flags already set in an existing file are
            kept; a decoder that msdr no longer has drops out, a new one arrives switched off.
Means:      Python 3.11+ (tomllib), msdr importable.
Provides:   CLI: <msdr venv>/bin/python kit/make_decoder_config.py [--out kit/tci-kit.toml]
Ensures:    the output parses as TOML; every msdr decoder id appears exactly once under [decoders].
Fails:      ImportError when msdr is not importable from this Python.

Why the groups: msdr runs one decoding session at a time, at one frequency (manager.start_decoding). Inside it,
decoders that take raw IQ cannot be mixed with decoders that take demodulated audio ("Run raw-IQ decoders separately
from audio decoders"), and audio decoders hear what the receiver demodulates, so the receiver's mode has to match.
The groups below show which switches can be on together.
"""
from __future__ import annotations

import argparse
import tomllib
from collections import defaultdict
from pathlib import Path

from msdr import __version__ as MSDR_VERSION
from msdr.decoder.registry import DECODERS

HERE = Path(__file__).resolve().parent
DEFAULT_ON = {"rtl433"}  # the calibration case: HDZ's Bresser-3CH station at 433.92 MHz

HEAD = """\
# TCI_transcode kit: settings and the msdr decoders that start with the kit.
# Generated by kit/make_decoder_config.py from msdr {msdr}; flip true/false freely, a rerun keeps your flags.
#
# One session, one frequency: msdr decodes at the receiver's VFO. Decoders that are on together must come from the
# same group below: raw IQ decoders cannot run beside audio decoders, and an audio decoder hears what the receiver
# demodulates, so set the receiver to the group's mode (NFM, USB, AM ...). The kit refuses a mixed set and says why.

[tci]
host = "127.0.0.1"
port = 50001            # SDR Oxide: the station radio serves TCI here by default

[bridge]
listen = "127.0.0.1:5454"
iq_rate = 500000        # samples/s; rtl_433 needs 500000 behind SDR Oxide, ADS-B needs 2400000
spots = true            # send decodes back to the receiver as TCI SPOT labels

[msdr]
port = 8765
browser = true          # open msdr's page after the start
"""


def khz(hz: float) -> str:
    return f"{hz / 1000:g} kHz" if hz < 1_000_000 else f"{hz / 1_000_000:g} MHz"


def rate(sps: int) -> str:
    return f"{sps / 1000:g} kS/s" if sps < 1_000_000 else f"{sps / 1_000_000:g} MS/s"


def group_of(spec) -> str:
    if spec.iq_only and tuple(spec.demodulators) == ("IQ",):
        return "IQ"
    return "/".join(spec.demodulators)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=HERE / "tci-kit.toml")
    args = ap.parse_args()

    old: dict[str, bool] = {}
    if args.out.exists():
        old = tomllib.loads(args.out.read_text()).get("decoders", {})

    groups: dict[str, list] = defaultdict(list)
    for spec in DECODERS.values():
        groups[group_of(spec)].append(spec)

    order = ["IQ"] + sorted(g for g in groups if g != "IQ")
    width = max(len(i) for i in DECODERS)
    lines = [HEAD.format(msdr=MSDR_VERSION), "[decoders]"]
    for g in order:
        specs = sorted(groups[g], key=lambda s: s.id)
        if g == "IQ":
            lines.append(f"\n# ── raw IQ ({len(specs)}): need the bridge's iq_rate at or above the rate shown,"
                         " and the signal inside the IQ window ──")
        elif g == "NFM":
            # manager.start_decoding: an all-NFM set decodes from msdr's own IQ path when the signal lies at least
            # 25 kHz inside the IQ window, and falls back to the receiver's audio otherwise.
            lines.append(f"\n# ── NFM ({len(specs)}): msdr demodulates from the IQ when the signal lies inside the IQ"
                         " window, otherwise it takes the receiver's audio in NFM ──")
        else:
            lines.append(f"\n# ── audio, receiver in {g} ({len(specs)}) ──")
        for s in specs:
            on = old.get(s.id, s.id in DEFAULT_ON)
            prog = ", ".join(s.binaries) if s.binaries else "built in"
            limit = f"IQ ≥ {rate(s.input_rate)}" if g == "IQ" else f"audio {rate(s.input_rate)}"
            note = f"{s.label} · {prog} · {limit} · {khz(s.default_bandwidth_hz)} wide"
            lines.append(f"{s.id.ljust(width)} = {'true ' if on else 'false'}  # {note}")
    text = "\n".join(lines) + "\n"

    parsed = tomllib.loads(text)["decoders"]
    assert set(parsed) == set(DECODERS), "every msdr decoder exactly once"
    args.out.write_text(text)
    gone = sorted(set(old) - set(DECODERS))
    print(f"{args.out}: {len(parsed)} decoders from msdr {MSDR_VERSION}, "
          f"{sum(parsed.values())} on" + (f"; dropped: {', '.join(gone)}" if gone else ""))


if __name__ == "__main__":
    main()
