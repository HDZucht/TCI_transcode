#!/usr/bin/env python3
"""Write kit/tci-kit.toml: the kit's settings, its rules, one on/off line per msdr decoder, and each decoder's facts.

Ends:       a config file that lists every decoder of the installed msdr, grouped the way msdr can run them together,
            states the rules in words ([rules]) and carries the numbers they need ([decoder_facts]), so the operator
            only flips true/false and kit/check_config.py can say exactly what is wrong without importing msdr.
Ways:       reads msdr's own decoder registry (msdr.decoder.registry.DECODERS), so the list follows the pinned msdr
            version instead of a hand-kept copy. Run it with msdr's Python. Settings and flags already in an existing
            file are kept; a decoder that msdr no longer has drops out, a new one arrives switched off.
Means:      Python 3.11+ (tomllib), msdr importable.
Provides:   CLI: <msdr venv>/bin/python kit/make_decoder_config.py [--out kit/tci-kit.toml]
Ensures:    the output parses as TOML; every msdr decoder id appears exactly once under [decoders] and under
            [decoder_facts]; the written file passes kit/check_config.py's structure checks.
Fails:      ImportError when msdr is not importable from this Python.

Where the rules come from (msdr 1.0.0rc10, msdr/decoder/manager.py, _start_decoding_locked): one decoding session at
a time, at one frequency; "Run raw-IQ decoders separately from audio decoders"; a raw IQ decoder needs the IQ rate at or
above its input rate and its full bandwidth inside the IQ span; a decoder whose program is missing is skipped with a
warning. Audio decoders hear what the receiver demodulates, so the ones that are on together must share a mode.
"""
from __future__ import annotations

import argparse
import json
import tomllib
from collections import defaultdict
from pathlib import Path

from msdr import __version__ as MSDR_VERSION
from msdr.decoder.registry import DECODERS

HERE = Path(__file__).resolve().parent
DEFAULT_ON = {"rtl433"}  # the calibration case: HDZ's Bresser-3CH station at 433.92 MHz

# Settings with their defaults and the comment shown beside them; an existing file's values win.
SETTINGS = {
    "tci": [
        ("host", "127.0.0.1", "the receiver's TCI server"),
        ("port", 50001, "SDR Oxide: the station radio serves TCI here by default"),
        ("vfo_offset_hz", 28000, "VFO distance from the IQ centre (SDR Oxide, RSP1A 2 MS/s, 433.92 MHz: 28 kHz)"),
    ],
    "bridge": [
        ("listen", "127.0.0.1:5454", "where msdr connects (SDRconnect API)"),
        ("iq_rate", 500000, "samples/s; the checker computes what each decoder that is on needs"),
        ("spots", True, "send decodes back to the receiver as TCI SPOT labels"),
    ],
    "msdr": [
        ("port", 8765, "msdr's web page"),
        ("browser", True, "open msdr's page after the start"),
    ],
}

HEAD = """\
# TCI_transcode kit: settings, rules, and the msdr decoders that start with the kit.
# Generated by kit/make_decoder_config.py from msdr {msdr}. Edit the values and flip true/false freely; a rerun keeps
# them. Check the file with: python3 kit/check_config.py   (errors stop the kit, warnings do not)
"""

RULES = """[rules]
# What kit/check_config.py enforces. Taken from msdr {msdr}, msdr/decoder/manager.py; [decoder_facts] holds the numbers.
one_session = "msdr runs one decoding session at a time, at one frequency: the receiver's VFO."
no_mix      = "ERROR: raw IQ decoders (path = IQ) and audio decoders cannot be on together."
one_mode    = "ERROR: audio decoders that are on together must share a receiver mode (modes in [decoder_facts]); set the receiver to that mode."
iq_rate     = "ERROR: bridge.iq_rate must reach the min_rate of every raw IQ decoder that is on."
iq_window   = "ERROR: a raw IQ decoder's signal must fit the IQ window: tci.vfo_offset_hz + width_hz/2 <= bridge.iq_rate/2."
names       = "ERROR: every key under [decoders] must be an msdr decoder id, and every value true or false."
programs    = "WARNING: a decoder whose program is not installed is skipped by msdr."
none_on     = "WARNING: no decoder is on; the kit starts the bridge and msdr only."
"""


def toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return json.dumps(v, ensure_ascii=False)


def khz(hz: float) -> str:
    return f"{hz / 1000:g} kHz" if hz < 1_000_000 else f"{hz / 1_000_000:g} MHz"


def rate(sps: int) -> str:
    return f"{sps / 1000:g} kS/s" if sps < 1_000_000 else f"{sps / 1_000_000:g} MS/s"


def path_of(spec) -> str:
    # The raw-IQ test of manager.start_decoding, verbatim.
    return "IQ" if spec.iq_only and tuple(spec.demodulators) == ("IQ",) else "audio"


def group_of(spec) -> str:
    return "IQ" if path_of(spec) == "IQ" else "/".join(spec.demodulators)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=HERE / "tci-kit.toml")
    args = ap.parse_args()

    old: dict = tomllib.loads(args.out.read_text()) if args.out.exists() else {}
    old_flags: dict = old.get("decoders", {})

    lines = [HEAD.format(msdr=MSDR_VERSION)]
    for section, items in SETTINGS.items():
        lines.append(f"[{section}]")
        have = old.get(section, {})
        w = max(len(k) for k, _, _ in items)
        for key, default, note in items:
            v = toml_value(have.get(key, default))
            lines.append(f"{key.ljust(w)} = {v.ljust(17)} # {note}")
        lines.append("")
    lines.append(RULES.format(msdr=MSDR_VERSION))

    groups: dict[str, list] = defaultdict(list)
    for spec in DECODERS.values():
        groups[group_of(spec)].append(spec)
    order = ["IQ"] + sorted(g for g in groups if g != "IQ")
    width = max(len(i) for i in DECODERS)

    lines.append("[decoders]")
    lines.append("# Only decoders from one group can be on together (rules no_mix, one_mode). USB/LSB and USB/NFM")
    lines.append("# decoders also fit the USB group, USB/NFM also the NFM group.")
    for g in order:
        specs = sorted(groups[g], key=lambda s: s.id)
        if g == "IQ":
            lines.append(f"\n# ── raw IQ ({len(specs)}): bridge iq_rate at or above the rate shown, signal inside the"
                         " IQ window ──")
        elif g == "NFM":
            # manager.start_decoding: an all-NFM set decodes from msdr's own IQ path when the signal lies at least
            # 25 kHz inside the IQ window, and falls back to the receiver's audio otherwise.
            lines.append(f"\n# ── audio, receiver in NFM ({len(specs)}): msdr demodulates from the IQ when the signal"
                         " lies inside the IQ window, otherwise it takes the receiver's NFM audio ──")
        else:
            lines.append(f"\n# ── audio, receiver in {g} ({len(specs)}) ──")
        for s in specs:
            on = old_flags.get(s.id, s.id in DEFAULT_ON)
            on = on if isinstance(on, bool) else s.id in DEFAULT_ON
            prog = ", ".join(s.binaries) if s.binaries else "built in"
            limit = f"IQ ≥ {rate(s.input_rate)}" if g == "IQ" else f"audio {rate(s.input_rate)}"
            note = f"{s.label} · {prog} · {limit} · {khz(s.default_bandwidth_hz)} wide"
            lines.append(f"{s.id.ljust(width)} = {'true ' if on else 'false'}  # {note}")

    lines.append(f"\n[decoder_facts]\n# Generated from msdr {MSDR_VERSION}; do not edit, rerun make_decoder_config.py instead.")
    for s in sorted(DECODERS.values(), key=lambda s: s.id):
        facts = {
            "label": s.label,
            "path": path_of(s),
            "modes": list(s.demodulators),
            "min_rate": int(s.input_rate),
            "width_hz": int(s.default_bandwidth_hz),
            "programs": list(s.binaries),
        }
        body = ", ".join(f"{k} = {json.dumps(v, ensure_ascii=False)}" for k, v in facts.items())
        lines.append(f"{s.id.ljust(width)} = {{ {body} }}")
    text = "\n".join(lines) + "\n"

    parsed = tomllib.loads(text)
    assert set(parsed["decoders"]) == set(DECODERS) == set(parsed["decoder_facts"]), "every msdr decoder exactly once"
    args.out.write_text(text)
    gone = sorted(set(old_flags) - set(DECODERS))
    print(f"{args.out}: {len(DECODERS)} decoders from msdr {MSDR_VERSION}, "
          f"{sum(parsed['decoders'].values())} on" + (f"; dropped: {', '.join(gone)}" if gone else ""))


if __name__ == "__main__":
    main()
